/**
 * Helper to fetch an exam by its unique ID
 */
export const getExamById = (examId: string): ExamData | undefined => {
  return mockExams.find((e) => e.id === examId);
};

/**
 * Helper to fetch an exam by lesson ID or quiz ID
 */
export const getExamByLessonId = (lessonId: string): ExamData | undefined => {
  return (
    mockExams.find((e) => e.lessonId === lessonId || e.id === lessonId) ||
    mockExams[0]
  );
};
